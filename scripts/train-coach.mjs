#!/usr/bin/env node
// Train the AI coach offline and write its weights into src/coach-prior.js (loaded by the game).
// Usage: npm run train   (seeded: the same data and weights every run; about 2 s, no dependencies)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { trainCoach } from "../src/coach-training.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const r = trainCoach();
const round = (x) => Math.round(x * 1e4) / 1e4;
const out = `// Generated by scripts/train-coach.mjs (npm run train). Do not edit by hand.
// Logistic regression trained on ${r.sizes.train} first attempts from simulated learners; test set ${r.sizes.test} rows from unseen learners.
// Test accuracy ${round(r.test.accuracy)} (baseline ${round(r.test.baselineAccuracy)}), test log loss ${round(r.test.logLoss)} (baseline ${round(r.test.baselineLogLoss)}).
export const COACH_PRIOR = ${JSON.stringify({ w: r.w.map(round), trainedOn: r.sizes.train, testAccuracy: round(r.test.accuracy), testLogLoss: round(r.test.logLoss) })};
`;
fs.writeFileSync(path.join(root, "src/coach-prior.js"), out);
console.log(`trained on ${r.sizes.train} rows; test accuracy ${(r.test.accuracy * 100).toFixed(1)} % vs baseline ${(r.test.baselineAccuracy * 100).toFixed(1)} %; log loss ${r.test.logLoss.toFixed(3)} vs ${r.test.baselineLogLoss.toFixed(3)}`);
console.log("weights:", r.w.map((x) => x.toFixed(2)).join(" "));
